def unit(v):
    return {"stringUnit": {"state": "translated", "value": v}}

def merge(path, d, lang="cs"):
    """Writes Czech into an Xcode-managed catalog, keeping Xcode's own keys and formatting."""
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    except FileNotFoundError:
        data = {"sourceLanguage": "en", "strings": {}, "version": "1.0"}
    strings = data.setdefault("strings", {})
    for k, v in d.items():
        entry = strings.setdefault(k, {})
        locs = entry.setdefault("localizations", {})
        if isinstance(v, tuple):
            locs[lang] = {"variations": {"plural": {form: unit(text) for form, text in v[1].items()}}}
        else:
            locs[lang] = unit(v)
    with open(path, "w", encoding="utf-8") as f:
        # Same layout Xcode writes, so builds don't reformat the file.
        json.dump(data, f, ensure_ascii=False, indent=2, separators=(",", " : "), sort_keys=True)
        f.write("\n")

